# 在 FastAPI 中，**带 `yield` 的依赖项**是**最特殊、最核心、你开发必用**的依赖写法，它和普通 `return` 依赖的**本质区别**只有一句话：

# # ✨ 核心特殊点（背会这句）
# **普通依赖：只做「前置操作」**
# **yield 依赖：支持「前置操作 + 后置收尾」两段式执行**
# 👉 **请求开始前干活 → 注入资源 → 请求结束后自动收尾**

# 这是 FastAPI 独有的**资源自动管理神器**，也是你之前学的 `get_db` 获取数据库连接的**底层原理**！

# ---

# ## 一、普通依赖 vs yield 依赖（一眼看懂）
# ### 1. 普通依赖（return）
# 只能**返回数据**，执行完就结束，**没有收尾能力**
# ```python
# # 普通依赖：只能传值，无法自动关闭资源
# def get_db_normal():
#     db = create_db()
#     return db  # 执行结束，连接一直开着 → 泄漏！
# ```

# ### 2. yield 依赖（神器）
# **两段代码**，自动拆分：
# - `yield` 之前：**请求前执行**（创建资源：连接DB、打开文件、登录校验）
# - `yield` 之后：**请求后自动执行**（销毁资源：关闭DB、关闭文件、释放锁）
# ```python
# # yield 依赖：自动创建 + 自动关闭（永不泄漏）
# def get_db():
#     db = create_db()  # 1. 请求前：创建连接
#     try:
#         yield db       # 2. 暂停，把db注入接口使用
#     finally:
#         db.close()    # 3. 请求后：**自动关闭**（无论接口是否报错！）
# ```

# ---

# ## 二、yield 依赖的 4 大「特殊能力」
# ### 1. 🔥 自动资源管理（最常用！）
# 专门管理**需要手动关闭**的资源：
# - 数据库连接（你正在用的 `get_db`）
# - Redis 连接
# - 文件打开/关闭
# - 网络请求

# **不用手动写关闭代码，框架自动帮你收尾**，彻底避免资源泄漏！

# ---

# ### 2. ✅ 绝对安全：报错也会执行收尾
# 就算接口代码崩溃、抛异常，**`yield` 后面的代码 `100%` 会执行**
# ```python
# def get_db():
#     db = SessionLocal()
#     try:
#         yield db
#     finally:
#         db.close()  # 接口报错、超时、正常结束 → 必执行！
# ```

# ---

# ### 3. 🧩 完全兼容依赖注入
# 用法和普通依赖一模一样，直接用 `Depends()` 注入：
# ```python
# # 直接注入，无任何学习成本
# @app.get("/test")
# def test(db: Annotated[Session, Depends(get_db)]):
#     return {"db": "使用中"}
# ```

# ---

# ### 4. 🚀 支持嵌套依赖
# 多个 yield 依赖可以嵌套，FastAPI 会**按顺序创建、逆序关闭**
# ```python
# # 依赖1：DB
# def get_db():
#     db = ...
#     yield db
#     db.close()

# # 依赖2：基于DB的用户校验
# def get_current_user(db: Session = Depends(get_db)):
#     yield user
#     # 自动先关user，再关db
# ```

# ---

# ## 三、强制规则（必须遵守）
# 1. **一个依赖只能有 1 个 `yield`**
# 2. **不能同时写 `return` 和 `yield`**
# 3. `yield` 后面的代码**不要抛异常**（会覆盖接口原有错误）
# 4. 收尾逻辑必须放在 `finally` 里（保证执行）

# ---

# ## 四、你最关心的：为什么数据库依赖必须用 yield？
# 因为：
# 1. 请求来 → 创建 DB 连接
# 2. 接口用连接查数据
# 3. **请求走 → 必须关闭连接**（不关闭会把数据库拖垮）

# `yield` 是 FastAPI 中**唯一能自动关闭连接**的方案！

# ---

# ## 五、极简总结（终极记忆）
# 1. **yield 依赖 = 前置创建 + 后置自动销毁**
# 2. **普通依赖 = 只创建，不销毁**
# 3. **核心用途**：管理数据库、Redis、文件等**需要手动关闭的资源**
# 4. **你的项目必用**：`get_db` 数据库依赖，就是标准 yield 依赖

# ---

# ### 一句话收尾
# **带 yield 的依赖，是 FastAPI 专为「资源自动管理」设计的超级特性，也是你写接口、操作数据库的核心依赖！**
